def test_streaming_request_with_an_answer_is_still_checked(bind_provider):
    provider = bind_provider(json.dumps({"ungrounded_claims": ["unsupported claim"]}))

    out = domain_supervisor_node({
        "response": _ANSWER,
        "retrieved_docs": ["chunk"],
        "_want_stream": True,
    })

    assert len(provider.calls) == 1, "a streamed answer must still be checked"
    assert out["ungrounded_claims"] == ["unsupported claim"]


def test_streamed_and_buffered_states_produce_the_same_result(bind_provider):
    """Transport is not an input to grounding."""
    bind_provider(json.dumps({"ungrounded_claims": ["c"]}))

    streamed = domain_supervisor_node({
        "response": _ANSWER, "retrieved_docs": ["chunk"], "_want_stream": True,
    })
    buffered = domain_supervisor_node({
        "response": _ANSWER, "retrieved_docs": ["chunk"],
    })

    assert streamed["ungrounded_claims"] == buffered["ungrounded_claims"]
    assert streamed["response"] == buffered["response"]


def test_empty_response_skips_without_calling_the_model(bind_provider):
    """Nothing to reconcile — skipped on its own merits, not because of streaming."""
    provider = bind_provider("{}")

    out = domain_supervisor_node({"response": "", "retrieved_docs": ["chunk"]})

    assert provider.calls == []
    assert out["ungrounded_claims"] == []
